CREATE INDEX CORE.WORKTREE_BY_WORKSPACE ON CORE.WORKTREE (WORKSPACE_ID, CREATED_AT, ID);
CREATE INDEX CORE.WORKTREE_BY_PARENT ON CORE.WORKTREE (PARENT_THREAD_ID, STATE, CREATED_AT);

