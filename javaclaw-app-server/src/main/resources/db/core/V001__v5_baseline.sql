CREATE TABLE CORE.ATTACHMENT_UPLOAD (
    ID CHAR(36) PRIMARY KEY,
    SCOPE_KIND VARCHAR(24) NOT NULL CHECK (SCOPE_KIND IN ('GLOBAL', 'WORKSPACE')),
    WORKSPACE_ID CHAR(36) REFERENCES CORE.WORKSPACE (ID) ON DELETE CASCADE,
    STATE VARCHAR(24) NOT NULL CHECK (STATE IN ('ACTIVE', 'COMPLETED', 'ABORTED', 'FAILED', 'EXPIRED')),
    MEDIA_TYPE VARCHAR(240) NOT NULL,
    EXPECTED_DIGEST CHAR(64) NOT NULL,
    EXPECTED_BYTES BIGINT NOT NULL CHECK (EXPECTED_BYTES BETWEEN 1 AND 67108864),
    RECEIVED_BYTES BIGINT NOT NULL CHECK (RECEIVED_BYTES BETWEEN 0 AND EXPECTED_BYTES),
    NEXT_CHUNK_INDEX INTEGER NOT NULL CHECK (NEXT_CHUNK_INDEX BETWEEN 0 AND 1024),
    REVISION BIGINT NOT NULL CHECK (REVISION > 0),
    ATTACHMENT_DIGEST CHAR(64) REFERENCES CORE.ATTACHMENT (DIGEST),
    FAILURE_REASON VARCHAR(500),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK ((SCOPE_KIND = 'WORKSPACE') = (WORKSPACE_ID IS NOT NULL)),
    CHECK ((STATE = 'COMPLETED') = (ATTACHMENT_DIGEST IS NOT NULL)),
    CHECK ((STATE IN ('ABORTED', 'FAILED', 'EXPIRED')) = (FAILURE_REASON IS NOT NULL))
);

CREATE INDEX CORE.IDX_ATTACHMENT_UPLOAD_ACTIVE
    ON CORE.ATTACHMENT_UPLOAD (STATE, EXPIRES_AT);

CREATE TABLE CORE.PROFILE (
    ID VARCHAR(240) NOT NULL,
    REVISION BIGINT NOT NULL CHECK (REVISION > 0),
    LIFECYCLE VARCHAR(32) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (ID, REVISION)
);

CREATE TABLE CORE.PROVIDER (
    ID VARCHAR(240) NOT NULL,
    REVISION BIGINT NOT NULL CHECK (REVISION > 0),
    LIFECYCLE VARCHAR(32) NOT NULL,
    PAYLOAD CLOB NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (ID, REVISION)
);

CREATE INDEX CORE.PROFILE_LATEST ON CORE.PROFILE (ID, REVISION DESC);
CREATE INDEX CORE.PROVIDER_LATEST ON CORE.PROVIDER (ID, REVISION DESC);

CREATE TABLE CORE.PROVIDER_VERIFICATION (
    IDEMPOTENCY_KEY VARCHAR(200) PRIMARY KEY,
    METHOD_NAME VARCHAR(160) NOT NULL,
    REQUEST_DIGEST CHAR(64) NOT NULL,
    PROVIDER_ID VARCHAR(240) NOT NULL,
    PROVIDER_REVISION BIGINT NOT NULL CHECK (PROVIDER_REVISION > 0),
    MODEL VARCHAR(500) NOT NULL,
    STATE VARCHAR(32) NOT NULL
        CHECK (STATE IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'TIMED_OUT', 'CANCELLED', 'UNKNOWN_OUTCOME')),
    RESULT_PAYLOAD CLOB,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK ((STATE = 'RUNNING') = (RESULT_PAYLOAD IS NULL)),
    FOREIGN KEY (PROVIDER_ID, PROVIDER_REVISION) REFERENCES CORE.PROVIDER (ID, REVISION)
);

CREATE TABLE CORE.PROMPT_OPTIMIZATION (
    ID CHAR(36) PRIMARY KEY,
    WORKSPACE_ID CHAR(36) NOT NULL REFERENCES CORE.WORKSPACE (ID),
    SOURCE_PROFILE_ID VARCHAR(240) NOT NULL,
    SOURCE_PROFILE_REVISION BIGINT NOT NULL CHECK (SOURCE_PROFILE_REVISION > 0),
    THREAD_ID CHAR(36) NOT NULL UNIQUE REFERENCES CORE.AGENT_THREAD (ID),
    TURN_ID CHAR(36) NOT NULL UNIQUE REFERENCES CORE.AGENT_TURN (ID),
    INSTRUCTION_REVISION VARCHAR(160) NOT NULL,
    INSTRUCTION_DIGEST CHAR(64) NOT NULL,
    ADOPTED_PROFILE_REVISION BIGINT,
    ADOPTED_AT TIMESTAMP WITH TIME ZONE,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (SOURCE_PROFILE_ID, SOURCE_PROFILE_REVISION)
        REFERENCES CORE.PROFILE (ID, REVISION),
    FOREIGN KEY (SOURCE_PROFILE_ID, ADOPTED_PROFILE_REVISION)
        REFERENCES CORE.PROFILE (ID, REVISION),
    CHECK ((ADOPTED_PROFILE_REVISION IS NULL) = (ADOPTED_AT IS NULL)),
    CHECK (ADOPTED_PROFILE_REVISION IS NULL OR ADOPTED_PROFILE_REVISION > SOURCE_PROFILE_REVISION)
);

CREATE INDEX CORE.PROMPT_OPTIMIZATION_BY_WORKSPACE
    ON CORE.PROMPT_OPTIMIZATION (WORKSPACE_ID, CREATED_AT DESC, ID);

CREATE TABLE CORE.PROFILE_BINDING (
