CREATE INDEX CORE.INPUT_REQUEST_BY_STATE ON CORE.INPUT_REQUEST (STATE, EXPIRES_AT);

CREATE TABLE CORE.EXTENSION_JOB (
    ID VARCHAR(240) PRIMARY KEY,
    EXTENSION_ID VARCHAR(240) NOT NULL,
    WORKSPACE_ID CHAR(36) NOT NULL REFERENCES CORE.WORKSPACE (ID),
    JOB_TYPE VARCHAR(240) NOT NULL,
    DEFINITION_ID VARCHAR(240) NOT NULL,
    DEFINITION_REVISION BIGINT NOT NULL CHECK (DEFINITION_REVISION > 0),
    FROZEN_INPUT CLOB NOT NULL,
    STATE VARCHAR(32) NOT NULL,
    REVISION BIGINT NOT NULL CHECK (REVISION > 0),
    CHECKPOINT CLOB NOT NULL,
    NEXT_UNIT_SEQUENCE BIGINT NOT NULL CHECK (NEXT_UNIT_SEQUENCE > 0),
    ACTIVE_UNIT_SEQUENCE BIGINT,
    ERROR_CODE VARCHAR(160),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (ACTIVE_UNIT_SEQUENCE IS NULL OR (ACTIVE_UNIT_SEQUENCE > 0 AND ACTIVE_UNIT_SEQUENCE < NEXT_UNIT_SEQUENCE)),
    CHECK ((STATE = 'FAILED') = (ERROR_CODE IS NOT NULL)),
    CHECK (ACTIVE_UNIT_SEQUENCE IS NULL OR STATE = 'RUNNING')
);

CREATE INDEX CORE.EXTENSION_JOB_BY_WORKSPACE
    ON CORE.EXTENSION_JOB (WORKSPACE_ID, UPDATED_AT DESC, ID);
CREATE INDEX CORE.EXTENSION_JOB_RUNNABLE
    ON CORE.EXTENSION_JOB (STATE, UPDATED_AT, ID);

CREATE TABLE CORE.EXTENSION_JOB_UNIT (
    JOB_ID VARCHAR(240) NOT NULL REFERENCES CORE.EXTENSION_JOB (ID) ON DELETE CASCADE,
    UNIT_SEQUENCE BIGINT NOT NULL CHECK (UNIT_SEQUENCE > 0),
    UNIT_ID VARCHAR(240) NOT NULL,
    INTENT CLOB NOT NULL,
    STATE VARCHAR(32) NOT NULL,
    RESULT_PAYLOAD CLOB,
    CHECKPOINT CLOB,
    TURN_ID CHAR(36) REFERENCES CORE.AGENT_TURN (ID),
    EFFECT_RECEIPT_KEY VARCHAR(500),
    ERROR_CODE VARCHAR(160),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (JOB_ID, UNIT_SEQUENCE),
    UNIQUE (JOB_ID, UNIT_ID),
    CHECK ((STATE = 'INTENT_RECORDED') = (COMPLETED_AT IS NULL)),
    CHECK ((STATE = 'COMPLETED') = (CHECKPOINT IS NOT NULL)),
    CHECK ((STATE = 'FAILED') = (ERROR_CODE IS NOT NULL))
);

